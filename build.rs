

fn main() {
    println!("cargo:rerun-if-changed=build.rs");

    let target_os = std::env::var("CARGO_CFG_TARGET_OS");
    if target_os.as_deref() == Ok("windows") {
        println!("cargo:rerun-if-changed=app.manifest");
        println!("cargo:rerun-if-changed=manifest.rc");
        embed_resource::compile("manifest.rc", embed_resource::NONE)
            .manifest_required()
            .unwrap();

        // The cdylib is the in-process activation server. Its `Dll*` entry
        // points are reached only by a loader's `GetProcAddress`, never
        // linked against, so the .def marks them PRIVATE to keep them out of
        // the generated import library; without it MSVC warns LNK4104 on
        // every build. This is a `cdylib-link-arg`, so the rlib, the demo bin
        // and the test harness are untouched.
        //
        // Generated rather than checked in, because the export list depends
        // on the feature set and naming a symbol a build does not define is
        // an unresolved-external link error, not a missing export.
        if std::env::var_os("CARGO_FEATURE_COMIO").is_some()
            && std::env::var("CARGO_CFG_TARGET_ENV").as_deref() == Ok("msvc")
        {
            let mut def = String::from(
                "; Generated by build.rs -- do not edit.
                 ;
                 ; Listing a name here does not make it exported: `no_mangle`
                 ; alone does that. What the file is for is PRIVATE, which keeps
                 ; these out of the import library so nothing binds to them
                 ; statically. See src/comio/activation.rs.
                 EXPORTS
                     DllGetActivationFactory PRIVATE
                     DllGetClassObject       PRIVATE
",
            );
            // Only a `dylib` build keeps the counts this one answers from.
            if std::env::var_os("CARGO_FEATURE_DYLIB").is_some() {
                def.push_str("    DllCanUnloadNow         PRIVATE
");
            }
            let out = std::path::Path::new(&std::env::var("OUT_DIR").unwrap())
                .join("comserver.def");
            std::fs::write(&out, def).expect("write comserver.def");
            println!("cargo:rustc-cdylib-link-arg=/DEF:{}", out.display());
        }
    }
    // https://github.com/microsoft/windows-app-rs
//     windows_bindgen::bindgen(
//
//         [
//             // "--no-deps",
//             "--in",
//             "default",
//             "winmd",
//             //
// // "--sys",
//             "--reference", "windows_future,flat,Windows.Foundation.IAsyncAction",
//
//             "--reference", "windows,skip-root,Windows.Foundation.*",
//             // "--reference", "windows,full,Windows.Foundation.TypedEventHandler",
//
//             // "Windows.Foundation",
//             "--out",
//             "src/bindings.rs",
//             // "--package",
//             // "--implement",
//             // "--specific-deps",
//                         // "--flat",
//                             // "--specific-deps",
//             "--filter",
//             // "DispatcherQueue",
//             // "DispatcherQueueController",
//             "Microsoft.UI.Dispatching",
//             // "!Microsoft.UI.Dispatching.IDispatcherQueueTimer",
//             // "!IDispatcherQueueShutdownStartingEventArgs",
//             // "!IDispatcherQueue3"
//
//         ]
//     ).unwrap();
//
//     ::windows_app::bootstrap::deploy::to_output_dir();
//
//     // Temporary workaround for https://github.com/microsoft/WindowsAppSDK/issues/2634
//     ::windows_app::build::embed_manifest(
//         r#"<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
//            <assembly manifestVersion="1.0" xmlns="urn:schemas-microsoft-com:asm.v1" />"#,
//     )
}